# Implementation overview
# -----------------------
#
# The direct evaluator is based on the ellipsoidal truncation method of
# Deconinck, Heil, Bobenko, van Hoeij and Schmies, *Computing Riemann Theta
# Functions*, Mathematics of Computation 73 (2004), 1417-1442. A Cholesky
# factorization of Im(tau) is used to enumerate the required lattice points,
# with the truncation radius selected from an incomplete-gamma tail bound.
# Half-integer upper gamma factors use an elementary exponential upper bound
# followed by positive-term recurrence, avoiding repeated high-precision erfc
# evaluations while keeping the truncation estimate conservative.
#
# Within each row of the lattice enumeration, one exponential initializes the
# summand and adjacent terms are generated by multiplicative recurrence.
# Quantities depending only on the period matrix are cached with the working
# precision included in the cache identity. Derivative truncation radii use a
# small bounded cache with shift norms rounded upward, so a cached radius is
# conservative for every argument in its bucket.
#
# When a lattice-volume estimate predicts a worthwhile saving, a partial
# Siegel reduction is applied using integer translations, unimodular basis
# changes and one-coordinate symplectic inversions. The basis changes use the
# Lenstra-Lenstra-Lovasz (LLL) lattice basis reduction algorithm to obtain a
# shorter, less skewed basis and expose a short direction for inversion. These
# transformations are recorded so that arguments, characteristics, values and
# derivative jets can be mapped consistently between the original and reduced
# coordinates. The choice between direct and reduced evaluation is a
# performance heuristic, not part of the error criterion; both paths use the
# same truncation bound.

